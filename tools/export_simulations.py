"""Export our call situations and objections as LiveKit simulation scenarios.

LiveKit's CLI can play a simulated caller against agent.py and judge each
conversation (see examples/data_capture_sim in github.com/livekit/agents):

    python tools/export_simulations.py          # writes data/simulations.yaml
    lk agent simulate text agent.py --scenarios data/simulations.yaml

Each scenario gives the simulated caller a persona and opening line in Kannada,
and the judge a description of what our agent must do.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.knowledge import load_kb, load_playbook  # noqa: E402
from app.scenarios import load_scenarios  # noqa: E402

OUT = ROOT / "data" / "simulations.yaml"

PERSONA = ("PERSONA: A person in Dharwad answering this phone call, usually at a small computer centre. "
           "Speak natural Dharwad/Hubballi Kannada in short sentences, mixing in English words "
           "like form, online, website. Play the situation in the opening line.")


def always_rules(kb):
    rules = ("In every turn the agent speaks one or two short sentences, stays calm and polite, "
             "never claims to be human and never asks for Aadhaar, OTP, bank or card details.")
    hidden = [p["name"] for p in kb["products"] if not p.get("price_approved")]
    if hidden:
        rules += f" It never states a price for {', '.join(hidden)}."
    return rules


def _q(text):
    # JSON strings are valid YAML double-quoted scalars.
    return json.dumps(text, ensure_ascii=False)


def build_simulations(scenarios, playbook, kb):
    always = always_rules(kb)
    items = []
    for s in scenarios["scenarios"]:
        test = s.get("test")
        if not test:
            continue
        tool = "" if s["action"] == "none" else f" It calls the {s['action']} tool."
        items.append({
            "id": f"SCN_{s['id']}",
            "label": s["situation"],
            "instructions": f"{PERSONA}\nOPENING LINE: \"{test['customer_says']}\"\n"
                            f"DO: Stay in this situation for one or two turns, then react naturally.",
            "expectations": f"{s['do']}{tool} {always}",
            "tags": {"kind": "situation", "category": s["category"]},
        })
    for o in playbook["objections"]:
        items.append({
            "id": f"SCN_obj_{o['id']}",
            "label": f"Objection: {o['objection_en']}",
            "instructions": f"{PERSONA}\nOPENING LINE: \"{o['objection_kn']}\"\n"
                            "DO: Repeat the concern once if the first answer does not address it, "
                            "then respond honestly to what the agent says.",
            "expectations": f"{o['approach']} {always}",
            "tags": {"kind": "objection", "category": "objection"},
        })
    return items


def to_yaml(items, kb):
    lines = [
        "# Generated by tools/export_simulations.py from call_scenarios.json and sales_playbook.json.",
        "# Do not edit by hand; edit the JSON files and run the script again.",
        "id: SCNG_sourcecode_sales_agent",
        f"name: {_q(kb['business']['name'] + ' voice agent: situations and objections')}",
        "",
        "scenarios:",
    ]
    for it in items:
        lines += [
            f"  - id: {it['id']}",
            f"    label: {_q(it['label'])}",
            f"    instructions: {_q(it['instructions'])}",
            f"    agent_expectations: {_q(it['expectations'])}",
            "    tags:",
            *[f"      {k}: {v}" for k, v in it["tags"].items()],
        ]
    return "\n".join(lines) + "\n"


def main():
    kb = load_kb()
    items = build_simulations(load_scenarios(), load_playbook(), kb)
    OUT.write_text(to_yaml(items, kb), encoding="utf-8")
    print(f"Wrote {len(items)} scenarios to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
